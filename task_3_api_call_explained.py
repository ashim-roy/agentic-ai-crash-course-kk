
#!/usr/bin/env python3
# The shebang tells Unix-like systems to execute this file using Python 3
# when the file is run as an executable.

import openai
# Imports the OpenAI Python SDK, which provides classes and methods
# to communicate with OpenAI's API.

import os
# Imports Python's built-in os module. We use it to read environment
# variables and create directories and files.

from dotenv import load_dotenv
# Imports load_dotenv() from python-dotenv.
# This lets us load configuration stored in our local .env file.

load_dotenv()
# Reads variables from .env and makes them available through os.environ.
# Importance: our API key stays outside the source code instead of
# being hardcoded into this Python file.

# Initialize the API client.
client = openai.OpenAI(
    api_key=os.getenv("OPENAI_API_KEY"),
    # os.getenv() reads the OPENAI_API_KEY environment variable.
    # The SDK uses this key to authenticate requests to the API.
    # If the variable is missing, client initialization will normally
    # fail because no API key was supplied.

    base_url=os.getenv("OPENAI_API_BASE") or "https://api.openai.com/v1"
    # Reads the API endpoint from OPENAI_API_BASE.
    # If that variable is missing or empty, Python's `or` selects
    # the official OpenAI API base URL instead.
    # This also allows us to use a compatible custom endpoint if needed.
)

# Send a request to the Chat Completions API and store the result.
response = client.chat.completions.create(
    # client.chat.completions.create() is an SDK method that sends
    # an HTTP request to the configured API endpoint.

    model="gpt-4.1-mini",
    # Selects the model that will generate the response.
    # The model name must be available to your API account.

    messages=[
        # The messages list represents the conversation sent to the model.
        # Each message is a dictionary containing a role and its content.

        {
            "role": "user",
            # Identifies this message as coming from the user.

            "content": "Hello AI, please introduce yourself"
            # Provides the actual text prompt sent to the model.
        }
    ]
)
# The API returns a ChatCompletion response object.
# It contains the generated answer, response metadata and token usage.

# Extract the generated text from the response object.
ai_text = response.choices[0].message.content
# response.choices contains the available response choices.
# [0] selects the first choice (normally the only choice requested).
# .message accesses that choice's message.
# .content retrieves the actual text generated by the model.
# ai_text now contains a Python string, rather than the full response.

print("API Call Successful!")
# Prints a confirmation message to the terminal.

print(f"\nAI said: {ai_text}")
# An f-string inserts the value of ai_text into the output.
# \n adds a newline before the answer.

print(f"\nTotal tokens used: {response.usage.total_tokens}")
# response.usage contains token-usage metadata returned by the API.
# total_tokens is the total input plus output tokens for this request.
# This is useful for monitoring usage and estimating API costs.

os.makedirs("markers", exist_ok=True)
# Creates a local markers directory if it doesn't already exist.
# exist_ok=True prevents an error when the directory already exists.

with open("markers/task3_api_call_complete.txt", "w") as f:
    # Opens the marker file in write mode.
    # `with` automatically closes the file after the block finishes.
    # The variable f refers to the opened file object.

    f.write("SUCCESS")
    # Writes a success marker so the course can track task completion.
    # This confirms the code reached this point; it is not an API test itself.
